// ============================================================
// CONCEPT: Pin, Unpin, and Self-Referential Futures
// ============================================================
//
// WHY THIS MATTERS FOR C# DEVELOPERS
// ------------------------------------
// C# async state machines are managed by the runtime — you never
// deal with pinning. In Rust, futures are structs that may contain
// pointers to themselves (self-referential). Moving such a struct
// would invalidate those pointers, so the compiler requires them
// to be "pinned" in memory before they can be polled.
//
// Pin<P> is a wrapper that guarantees: once placed, the value at
// *P will not move for the duration of its lifetime.
//
// Unpin — a marker trait. Types that implement Unpin are safe to
// move even when pinned (e.g., i32, String, Vec<T>). Most ordinary
// types are Unpin. Futures generated by async fn are NOT Unpin.
//
// RUN: cargo run --bin pin_unpin
// ============================================================

use std::marker::PhantomPinned;
use std::pin::Pin;

fn main() {
    println!("=== Pin and Unpin ===\n");

    pin_basics();
    pin_on_stack();
    pin_on_heap();
    self_referential_demo();
    practical_pin();
}

// ---- 1. Pin basics -------------------------------------------------

fn pin_basics() {
    println!("--- What Unpin Means ---");

    // Most types are Unpin — they can be freely moved.
    let mut x: i32 = 42;
    // Pin wrapping an Unpin type adds no restrictions:
    let pinned: Pin<&mut i32> = Pin::new(&mut x);
    println!("pinned i32 value: {}", *pinned);

    // Because i32: Unpin, we can still get &mut i32 back:
    let r: &mut i32 = Pin::into_inner(pinned);
    *r = 99;
    println!("mutated through Pin<&mut i32>: {x}");

    println!("\nUnpin types (safe to move when pinned):");
    println!("  i8..i128, u8..u128, f32/f64, bool, char");
    println!("  String, Vec<T>, Box<T>, Arc<T>, HashMap, ...");
    println!("  Tuples/arrays/structs of Unpin types");
    println!("\n!Unpin types (must NOT move once pinned):");
    println!("  Futures generated by async fn");
    println!("  Types that manually opt-out with PhantomPinned");
}

// ---- 2. Pinning on the stack ---------------------------------------

fn pin_on_stack() {
    println!("\n--- Stack Pinning (tokio::pin! macro) ---");

    // tokio::pin! shadows the variable with a Pin<&mut T> in place,
    // preventing any subsequent moves. It's the standard way to pin
    // a future created inline on the stack.

    async fn my_future(label: &str) -> String {
        tokio::time::sleep(std::time::Duration::from_millis(1)).await;
        format!("{label} done")
    }

    // In an async context you'd do:
    //   let fut = my_future("hello");
    //   tokio::pin!(fut);
    //   fut.await;
    //
    // tokio::pin!(fut) expands to:
    //   let mut fut = fut;
    //   let mut fut = unsafe { Pin::new_unchecked(&mut fut) };
    // This is safe because `fut` is now borrowed for the rest of the scope,
    // so it cannot be moved.

    println!("  tokio::pin!(fut) pins a future to the local stack frame");
    println!("  The original binding is shadowed by Pin<&mut Future>");
    println!("  C# analogy: async state machine pinning is automatic (GC heap)");
}

// ---- 3. Pinning on the heap ----------------------------------------

fn pin_on_heap() {
    println!("\n--- Heap Pinning (Box::pin) ---");

    // Box::pin(value) allocates on the heap AND pins it there.
    // The resulting Pin<Box<T>> can be stored in structs or passed around.

    async fn long_running(id: u32) -> u32 {
        tokio::time::sleep(std::time::Duration::from_millis(1)).await;
        id * 2
    }

    // Create an erased, pinned, heap-allocated future:
    // Pin<Box<dyn Future<Output = u32>>>
    let _fut: Pin<Box<dyn std::future::Future<Output = u32>>> =
        Box::pin(long_running(21));

    println!("  Box::pin(future) → Pin<Box<dyn Future<Output=T>>>");
    println!("  Use when you need to store futures in structs or Vec");
    println!("  Slightly higher cost than stack pinning (heap alloc)");

    // Common pattern: storing multiple heterogeneous futures:
    let futures: Vec<Pin<Box<dyn std::future::Future<Output = u32>>>> = vec![
        Box::pin(long_running(1)),
        Box::pin(long_running(2)),
        Box::pin(long_running(3)),
    ];
    println!("  Vec of pinned futures: {} items", futures.len());
}

// ---- 4. Self-referential struct demo -------------------------------

struct SelfRef {
    data: String,
    // Pointer to part of `data` — valid only while data doesn't move:
    ptr: *const u8,
    _pin: PhantomPinned, // opt out of Unpin
}

impl SelfRef {
    fn new(s: &str) -> Self {
        SelfRef {
            data: s.to_string(),
            ptr: std::ptr::null(), // filled in init()
            _pin: PhantomPinned,
        }
    }

    // SAFETY: must only be called while the struct is already pinned
    fn init(self: Pin<&mut Self>) {
        let self_ptr = unsafe { self.get_unchecked_mut() };
        let data_ptr = self_ptr.data.as_ptr();
        self_ptr.ptr = data_ptr;
    }

    fn value(self: Pin<&Self>) -> &str {
        // SAFETY: ptr was set to point into self.data while pinned;
        // since we're still pinned, the pointer is still valid.
        unsafe {
            let slice = std::slice::from_raw_parts(self.ptr, self.data.len());
            std::str::from_utf8_unchecked(slice)
        }
    }
}

fn self_referential_demo() {
    println!("\n--- Self-Referential Struct (why Pin exists) ---");

    // Stack-pin SelfRef:
    let mut sr = SelfRef::new("hello from self-ref");
    // SAFETY: we never move sr after this point
    let mut pinned = unsafe { Pin::new_unchecked(&mut sr) };
    pinned.as_mut().init();
    println!("  self-referential value: '{}'", pinned.as_ref().value());

    // If we tried to move sr here, the ptr would dangle — but the borrow
    // checker prevents it because `pinned` borrows `sr` for the rest of scope.

    println!("  PhantomPinned prevents the type from being Unpin");
    println!("  async fn state machines do the same thing internally");
}

// ---- 5. Practical Pin usage ----------------------------------------

fn practical_pin() {
    println!("\n--- Practical Patterns ---");

    println!(r#"
Pattern 1: select! with reusable futures
-----------------------------------------
  let fut = some_async_fn();
  tokio::pin!(fut);          // Pin to stack, reuse across select! arms
  loop {{
      tokio::select! {{
          r = &mut fut => {{ ... break; }}
          _ = timeout  => {{ ... }}
      }}
  }}

Pattern 2: store futures in a struct
--------------------------------------
  struct Task {{
      inner: Pin<Box<dyn Future<Output = ()> + Send>>,
  }}
  impl Task {{
      fn new(f: impl Future<Output=()> + Send + 'static) -> Self {{
          Task {{ inner: Box::pin(f) }}
      }}
  }}

Pattern 3: FuturesUnordered (already pinned internally)
---------------------------------------------------------
  let mut futs = FuturesUnordered::new();
  futs.push(async_fn_1());   // push moves futures in, FuturesUnordered pins them
  futs.push(async_fn_2());
  while let Some(r) = futs.next().await {{ ... }}

C# comparison
--------------
  C# runtime pins async state machines on the GC heap automatically.
  Rust requires explicit pinning because it does not have a GC.
  tokio::pin!  ≈  "pin this on my current stack frame"
  Box::pin     ≈  "allocate on the heap and pin there"
"#);
}

// ---- Summary -------------------------------------------------------
//
// Pin<P> — guarantees the value behind pointer P won't move
// Unpin  — marker: safe to move even when nominally pinned
// !Unpin — opt-out via PhantomPinned; future state machines are !Unpin
//
// Rules:
//   • Ordinary types (i32, String, Vec) are Unpin — Pin adds nothing
//   • async fn futures are !Unpin — must be pinned before poll()
//   • tokio::pin!(x) → stack pinning (zero heap cost)
//   • Box::pin(x)    → heap pinning (stores + owns the pinned value)
//   • Pin<Box<dyn Future>> is the trait-object form for stored futures
